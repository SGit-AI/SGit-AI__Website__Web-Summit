  console.log('external requests:', ext.length ? ext : 'none'); console.log('errors:', errs.length ? errs : 'none')
  const m = await b.newPage({ viewport: { width: 390, height: 844 } }); await m.addInitScript(shim)
  await m.goto('http://localhost:8765/index.html'); await m.waitForTimeout(500); await m.click('.wsm-list li:nth-child(1) button'); await m.waitForTimeout(400)
