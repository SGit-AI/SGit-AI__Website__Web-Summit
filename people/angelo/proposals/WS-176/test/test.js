const ROOT = path.join(__dirname, 'vault'), OUT = path.join(__dirname, 'shots')
fs.mkdirSync(OUT, { recursive: true })
const srv = http.createServer((q, r) => { const f = path.join(ROOT, decodeURIComponent(q.url.split('?')[0])); if (!f.startsWith(ROOT) || !fs.existsSync(f) || fs.statSync(f).isDirectory()) { r.writeHead(404); return r.end() } r.end(fs.readFileSync(f)) }).listen(8765)
